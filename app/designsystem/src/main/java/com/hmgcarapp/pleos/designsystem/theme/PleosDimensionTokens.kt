fun pleosWindowFor(formFactor: PleosFormFactor): PleosWindowDimensions = when (formFactor) {
    PleosFormFactor.ConnectS -> PleosWindowConnectS
    PleosFormFactor.ConnectL -> PleosWindowConnectL
    PleosFormFactor.ConnectW -> PleosWindowConnectW
