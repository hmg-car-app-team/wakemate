fun pleosDimensionsFor(formFactor: PleosFormFactor): PleosDimensions = when (formFactor) {
    PleosFormFactor.ConnectS -> PleosDimensionsConnectS
    PleosFormFactor.ConnectL -> PleosDimensionsConnectL
    PleosFormFactor.ConnectW -> PleosDimensionsConnectW
    PleosFormFactor.ConnectWaterfall -> PleosDimensionsConnectWaterfall
}

